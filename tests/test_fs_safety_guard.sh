#!/usr/bin/env bash
set -euo pipefail
ROOT_DIR="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
FS="$ROOT_DIR/FS-hardening.sh"
fail(){ echo "[FAIL] $*" >&2; exit 1; }
pass(){ echo "[PASS] $*"; }
grep -Fq '["/var"]="noexec,nosuid,nodev"' "$FS" || fail "/var debe conservar noexec,nosuid,nodev"
grep -Fq '["/home"]="noexec,nosuid,nodev"' "$FS" || fail "/home debe incluir noexec,nosuid,nodev"
grep -Fq '["/dev/shm"]="noexec,nosuid,nodev"' "$FS" || fail "/dev/shm debe exigir siempre noexec,nosuid,nodev"
grep -Fq 'local -a required=("noexec" "nosuid" "nodev") approved_array=()' "$FS" || fail "/dev/shm debe verificar las tres opciones obligatorias"
grep -Fq 'apply_mount_options_from_fstab()' "$FS" || fail "los cambios de montaje deben seguir el flujo persistir-recargar-remontar"
grep -Fq 'persist_mount_options "$mount_point" "$add_if_missing" "$spec"' "$FS" || fail "el flujo debe persistir FSTAB antes de remontar"
grep -Fq 'systemctl daemon-reload' "$FS" || fail "debe recargar systemd tras editar FSTAB"
grep -Fq 'mount -o remount "$mount_point"' "$FS" || fail "el remount debe leer las opciones persistidas, sin opciones adicionales"
! grep -Fq 'mount -o remount,"$new_opts"' "$FS" || fail "no debe aplicar opciones manuales al remount"
grep -Fq 'if [ "$mount_point" = "/dev/shm" ] && [ -n "$spec" ]; then' "$FS" || fail "/dev/shm debe usar persistencia canónica especial"
grep -Fq 'echo "[✓] /etc/fstab normalizado para /dev/shm: $spec"' "$FS" || fail "debe confirmar la normalización de /dev/shm"
helper="$(sed -n '/^apply_mount_options_from_fstab()/,/^}/p' "$FS")"
persist_line="$(printf '%s\n' "$helper" | grep -nF 'persist_mount_options "$mount_point"' | head -1 | cut -d: -f1)"
reload_line="$(printf '%s\n' "$helper" | grep -nF 'systemctl daemon-reload' | head -1 | cut -d: -f1)"
remount_line="$(printf '%s\n' "$helper" | grep -nF 'mount -o remount "$mount_point"' | head -1 | cut -d: -f1)"
[ -n "$persist_line" ] && [ -n "$reload_line" ] && [ -n "$remount_line" ] || fail "el flujo debe contener persistencia, daemon-reload y remount"
[ "$persist_line" -lt "$reload_line" ] && [ "$reload_line" -lt "$remount_line" ] || fail "el orden debe ser persistir FSTAB, recargar systemd y remontar"
! grep -Fq 'Aplicar correcciones automáticamente tras el preflight' "$FS" || fail "la ayuda no debe prometer correcciones automáticas sin confirmación"
! grep -Fq '["/proc"]="hidepid=2"' "$FS" || fail "/proc no debe aplicar hidepid=2"
! grep -Fq 'configure_proc()' "$FS" || fail "no debe existir el control hidepid"
grep -Fq 'if [ "${ORANGEBOX_ASSUME_YES:-0}" = "1" ]' "$FS" || fail "debe respetar la aprobación explícita del orquestador"
! grep -Fq 'ORANGEBOX_ASSUME_YES=1; export ORANGEBOX_ASSUME_YES' "$FS" || fail "el módulo standalone no debe autoaprobar sus propios cambios"
grep -Fq 'confirmación individual antes de cada cambio sensible' "$FS" || fail "--fix standalone debe anunciar confirmación individual"
! grep -Fq 'Aplicar las propuestas automáticamente, sin preguntas' "$FS" || fail "la ayuda no debe prometer un comportamiento distinto"
grep -Fq 'Qué hace: bloquea la ejecución directa de binarios en $mount_point' "$FS" || fail "noexec necesita descripción clara"
pass "filesystem exige noexec,nosuid,nodev en /var, /home y /dev/shm; no activa hidepid=2"
