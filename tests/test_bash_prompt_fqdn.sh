#!/usr/bin/env bash
# Test the prompt FQDN and Readline mode in isolated interactive shells.
set -euo pipefail

ROOT_DIR="$(CDPATH= cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
TMP_DIR="$(mktemp -d "$ROOT_DIR/.orangebox-prompt-test.XXXXXX")"
trap 'rm -rf "$TMP_DIR"' EXIT
MOCK_BIN="$TMP_DIR/bin"
MOCK_HOME="$TMP_DIR/home"
mkdir -p "$MOCK_BIN" "$MOCK_HOME"

cat > "$MOCK_BIN/hostname" <<'MOCK_HOSTNAME'
#!/usr/bin/env bash
if [ "${1:-}" = "-f" ]; then
  printf '%s\n' 'srv19.cloudlatam.cl'
else
  printf '%s\n' 'srv19'
fi
MOCK_HOSTNAME
chmod 755 "$MOCK_BIN/hostname"

fail() {
  printf '[FAIL] %s\n' "$*" >&2
  exit 1
}
pass() {
  printf '[PASS] %s\n' "$*"
}

# Extract the actual generated profile body from the core hardening script.
awk '
  !found && /<<.ORANGEBOX_BASH./ { found=1; next }
  found && /^ORANGEBOX_BASH$/ { exit }
  found { print }
  END { if (!found) exit 1 }
' "$ROOT_DIR/linux-hardening.sh" > "$TMP_DIR/core-profile.sh" ||
  fail "no se pudo extraer el perfil generado por linux-hardening.sh"

# Extract the profile generated by the standalone bash-hardening module.
awk '
  !found && /cat >"\$PROFILE_D" <<.EOF./ { found=1; next }
  found && /^EOF$/ { exit }
  found { print }
  END { if (!found) exit 1 }
' "$ROOT_DIR/bash-hardening.sh" > "$TMP_DIR/standalone-profile.sh" ||
  fail "no se pudo extraer el perfil generado por bash-hardening.sh"

bash -n "$TMP_DIR/core-profile.sh" || fail "sintaxis del perfil core"
bash -n "$TMP_DIR/standalone-profile.sh" || fail "sintaxis del perfil standalone"

run_profile_test() {
  local label="$1" profile="$2" hook="$3"
  local output="$TMP_DIR/$label.out" errors="$TMP_DIR/$label.err"
  local runner="$TMP_DIR/$label-runner.sh"
  local launcher="$TMP_DIR/$label-launcher.sh"

  cat > "$runner" <<'CHECK_PROFILE'
set -eo pipefail
source "$PROFILE_FILE" >/dev/null
# Simula el set -o vi que aparece al final del .bashrc de srv19.
set -o vi
"$PROMPT_HOOK"

case "$PS1" in
  *srv19.cloudlatam.cl*) ;;
  *) printf "FQDN ausente en PS1: %s\\n" "$PS1" >&2; exit 31 ;;
esac

set -o | grep -Eq "^emacs[[:space:]]+on$" || {
  echo "La función del prompt no restauró el modo Emacs" >&2
  exit 32
}
bind -q beginning-of-line 2>&1 | grep -Fq "C-a" || {
  echo "Ctrl+A no está asociado a beginning-of-line" >&2
  exit 33
}
bind -q end-of-line 2>&1 | grep -Fq "C-e" || {
  echo "Ctrl+E no está asociado a end-of-line" >&2
  exit 34
}
CHECK_PROFILE

  cat > "$launcher" <<'LAUNCH_INTERACTIVE'
#!/usr/bin/env bash
exec bash --noprofile --norc -i -c 'source "$RUN_SCRIPT"; exit'
LAUNCH_INTERACTIVE
  chmod 755 "$launcher"

  if ! command -v script >/dev/null 2>&1; then
    fail "no está disponible util-linux script para crear una pseudo-terminal"
  fi

  if ! env \
    PATH="$MOCK_BIN:$PATH" \
    HOME="$MOCK_HOME" \
    HISTFILE="$TMP_DIR/$label.history" \
    PROFILE_FILE="$profile" \
    PROMPT_HOOK="$hook" \
    RUN_SCRIPT="$runner" \
    script -qec "$launcher" /dev/null >"$output" 2>"$errors"; then
    cat "$output" >&2 || true
    cat "$errors" >&2 || true
    fail "$label: hostname FQDN o modo Emacs/Readline incorrecto"
  fi

  pass "$label: PS1 muestra FQDN y el hook restaura Emacs/Ctrl+A/Ctrl+E tras set -o vi"
}

run_profile_test "core" "$TMP_DIR/core-profile.sh" "orangebox_pre_prompt"
run_profile_test "standalone" "$TMP_DIR/standalone-profile.sh" "orangebox_history_guard"
printf 'Todas las pruebas del prompt Bash pasaron.\n'
